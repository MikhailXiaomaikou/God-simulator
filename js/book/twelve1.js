      const d = Math.hypot(tx, ty) || 1; tx /= d; ty /= d;
      const nx = flip ? ty : -ty, ny = flip ? -tx : tx;
      const k = i / N;
      const prof = k < 0.22 ? 0.78 + 0.22 * Math.sin((k / 0.22) * Math.PI / 2) : 1 - Math.pow((k - 0.22) / 0.78, 1.45) * 0.9;
